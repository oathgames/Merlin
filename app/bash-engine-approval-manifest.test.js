// REGRESSION GUARD (2026-11-20, bash-approval-followup)
//
// Single source of truth for which engine actions the Bash approval path
// must card. engine-approval-actions.json is generated in autocmo-core by
// approval_gated_actions_test.go from the main.go dispatcher: every action
// whose case reaches requireApproval, a spend cap, the spend-pause check, the
// daily-budget validator, a .Approved read, or a live-status / budget field
// write. That core test fails when main.go drifts from its copy; this test
// fails when an action in the copy reaches the engine from Bash uncarded.
//
// Every assertion drives the real routeBash with a real engine command, so
// the classification under test is the one handleToolApproval dispatches on.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const route = require('./bash-approval-route');

const MANIFEST_PATH = path.join(__dirname, 'engine-approval-actions.json');
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
const GATED = manifest.actions;
const BIN = '.claude/tools/Merlin.exe';
const call = (action, extra = '') =>
  `${BIN} --cmd '{"action":"${action}","brand":"acme"${extra}}'`;
const CARDED_ROUTES = new Set(['spend', 'destructive']);

test('manifest is the generated core file, sorted and non-trivial', () => {
  assert.ok(Array.isArray(GATED) && GATED.length >= 100, `expected 100+ gated actions, got ${GATED && GATED.length}`);
  assert.deepEqual([...GATED].sort(), GATED, 'manifest actions must be sorted (generated file)');
  assert.match(manifest._comment, /GENERATED by approval_gated_actions_test\.go/);
});

test('app copy is identical to the core manifest when the core repo is present', (t) => {
  const candidates = [
    path.join(__dirname, '..', '..', 'autocmo-core', 'approval_gated_actions.json'),
    path.join(__dirname, '..', '..', '..', 'autocmo-core', 'approval_gated_actions.json'),
  ];
  const core = candidates.find((p) => fs.existsSync(p));
  if (!core) {
    // Public-repo CI has no core checkout. The core test pins the same file.
    t.diagnostic('autocmo-core not present; core-side drift test covers this');
    return;
  }
  const norm = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
  assert.equal(norm(MANIFEST_PATH), norm(core),
    'app/engine-approval-actions.json is stale: copy autocmo-core/approval_gated_actions.json over it');
});

test('every engine-gated action cards on the Bash path or is exempt with a reason', () => {
  const uncarded = [];
  for (const action of GATED) {
    const r = route.routeBash(call(action, ',"approved":true,"dailyBudget":900'));
    if (CARDED_ROUTES.has(r.route) || r.route === 'card-unreadable' || r.route === 'deny-ambiguous') continue;
    if (Object.prototype.hasOwnProperty.call(route.ENGINE_GATED_EXEMPT, action)) continue;
    uncarded.push(`${action} -> ${r.route}`);
  }
  assert.deepEqual(uncarded, [],
    'engine-gated actions reach the engine from Bash with no card. Add each to BASH_SPEND or ' +
    'BASH_CARDED_DESTRUCTIVE (mirroring mcp-approval-policy.js), or to ENGINE_GATED_EXEMPT with a reason.');
});

test('every ENGINE_GATED_EXEMPT entry is a live gated action with a real reason', () => {
  const gated = new Set(GATED);
  for (const [action, reason] of Object.entries(route.ENGINE_GATED_EXEMPT)) {
    assert.ok(gated.has(action), `${action} is exempted but no longer engine-gated; remove the stale entry`);
    assert.ok(typeof reason === 'string' && reason.length >= 40, `${action} needs a real reason`);
  }
});

test('no exempt action is also carded (one decision per action)', () => {
  for (const action of Object.keys(route.ENGINE_GATED_EXEMPT)) {
    assert.ok(!route.BASH_SPEND.has(action), `${action} is both exempt and in BASH_SPEND`);
    assert.ok(!route.BASH_CARDED_DESTRUCTIVE.has(action), `${action} is both exempt and in BASH_CARDED_DESTRUCTIVE`);
  }
});

test('every BASH_SPEND action routes to the spend card through routeBash', () => {
  for (const action of route.BASH_SPEND) {
    // Batch status with no batchStatus value cannot prove it only pauses.
    const r = route.routeBash(call(action, ',"dailyBudget":20'));
    assert.equal(r.route, 'spend', `${action} must card as spend, got ${r.route}`);
    assert.equal(r.action, action);
  }
});

test('every BASH_CARDED_DESTRUCTIVE action routes to the generic card through routeBash', () => {
  for (const action of route.BASH_CARDED_DESTRUCTIVE) {
    const r = route.routeBash(call(action));
    assert.equal(r.route, 'destructive', `${action} must card, got ${r.route}`);
  }
});

test('kills stay uncarded (Bash meta-kill policy) and reads stay uncarded', () => {
  for (const action of ['meta-kill', 'snapchat-kill', 'pinterest-kill', 'twitter-kill', 'meta-insights', 'meta-list-adsets']) {
    assert.equal(route.routeBash(call(action)).route, 'other', `${action} must not card`);
  }
});

test('batch status cards unless it can only pause', () => {
  for (const action of route.BASH_PAUSE_ONLY_STATUS) {
    assert.equal(route.routeBash(call(action, ',"batchStatus":"PAUSED","adIds":["1"]')).route, 'other');
    // Only the exact PAUSED spelling is uncarded; anything else fails closed.
    assert.equal(route.routeBash(call(action, ',"batchStatus":"paused","adIds":["1"]')).route, 'spend');
    assert.equal(route.routeBash(call(action, ',"batchStatus":"ACTIVE","adIds":["1"]')).route, 'spend');
    assert.equal(route.routeBash(call(action, ',"adIds":["1"]')).route, 'spend');
    // Go binds the LAST key in any case: a trailing ACTIVE wins.
    assert.equal(route.routeBash(call(action, ',"batchStatus":"PAUSED","BatchStatus":"ACTIVE"')).route, 'spend');
    assert.equal(route.routeBash(call(action, ',"batchStatus":"ACTIVE","batchStatus":"PAUSED"')).route, 'other');
  }
});

test('newly gated actions from this change card (named anchors)', () => {
  const spend = ['meta-activate', 'meta-bulk-push', 'google-ads-budget', 'openai-ads-budget', 'openai-ads-activate',
    'linkedin-budget', 'tiktok-gmv-max-update-roi', 'pinterest-activate', 'twitter-activate', 'snapchat-create-campaign'];
  for (const a of spend) assert.equal(route.routeBash(call(a)).route, 'spend', a);
  const destructive = ['klaviyo-campaign-send', 'gtm-publish', 'google-analytics-create-key-event',
    'meta-upload-customer-list', 'meta-set-frequency-cap', 'slack-post'];
  for (const a of destructive) assert.equal(route.routeBash(call(a)).route, 'destructive', a);
  // Only push-equivalents are in-cap auto-approve eligible.
  for (const a of ['meta-activate', 'google-ads-budget', 'openai-ads-budget', 'meta-bulk-push']) {
    assert.ok(!route.BASH_PUSH_ONLY.has(a), `${a} must never be in BASH_PUSH_ONLY`);
  }
});
